/**
 * Captures the React SideNavigation's server-rendered markup for every case in
 * `src/testing/fixtures.goldenCases.ts` and writes it to
 * `src/testing/fixtures.reactGolden.ts`, the reference the Svelte markup parity
 * test compares against.
 *
 * Run from this package after building the React app package:
 * `bun scripts/captureReactGolden.tsx`. React is resolved from the React
 * package.
 */
import { writeFileSync } from "node:fs";
import { goldenCases } from "../src/testing/fixtures.goldenCases.ts";

const reactPackage = new URL("../../../react/ds-app/", import.meta.url);
const resolve = (specifier: string) =>
  Bun.resolveSync(specifier, reactPackage.pathname);
const { createElement } = await import(resolve("react"));
const { renderToStaticMarkup } = await import(resolve("react-dom/server"));
const { SideNavigation } = await import(
  new URL("dist/esm/index.js", reactPackage).pathname
);

const span = (text: unknown) =>
  typeof text === "string" ? createElement("span", null, text) : undefined;
const handler = (flag: unknown) => (flag ? () => {} : undefined);

// biome-ignore lint/suspicious/noExplicitAny: case props are data
type Data = any;

const leaf = (item: Data) => ({
  ...item,
  slot: span(item.slot),
  onClick: handler(item.onClick),
});
const tree = (root: Data) =>
  root && {
    ...root,
    items: root.items?.map((group: Data) => ({
      ...group,
      items: group.items?.map((entry: Data) =>
        entry.items ? { ...entry, items: entry.items.map(leaf) } : leaf(entry),
      ),
    })),
  };
const footer = (root: Data) =>
  root && {
    ...root,
    items: root.items.map((entry: Data) =>
      entry.items ? { ...entry, items: entry.items.map(leaf) } : leaf(entry),
    ),
  };
const context = (item: Data) => ({ ...item, badge: span(item.badge) });

export function toReactProps(props: Data): Data {
  const { brand, root, footerRoot, contextSwitcher, messages, ...rest } = props;
  return {
    ...rest,
    brand: span(brand),
    root: tree(root),
    footerRoot: footer(footerRoot),
    contextSwitcher: contextSwitcher && {
      ...contextSwitcher,
      currentContext: context(contextSwitcher.currentContext),
      contexts: contextSwitcher.contexts.map(context),
      onCreateContext: handler(contextSwitcher.onCreateContext),
    },
    messages:
      messages &&
      Object.fromEntries(
        Object.entries(messages).map(([key, text]) => [key, () => text]),
      ),
  };
}

const golden: Record<string, string> = {};
for (const [key, { props }] of Object.entries(goldenCases)) {
  golden[key] = renderToStaticMarkup(
    createElement(SideNavigation, toReactProps(props)),
  );
}

writeFileSync(
  new URL("../src/testing/fixtures.reactGolden.ts", import.meta.url),
  `// Generated by scripts/captureReactGolden.tsx; do not edit by hand.\nexport const reactGolden: Record<string, string> = ${JSON.stringify(golden, null, 2)};\n`,
);
