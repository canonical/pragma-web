/**
 * Captures the React form package's server-rendered markup for every case in
 * `src/testing/fixtures.goldenCases.ts` and writes it to
 * `src/testing/fixtures.reactGolden.ts`, the reference the Svelte markup parity
 * test compares against.
 *
 * Run from this package after building the React form package:
 * `bun scripts/captureReactGolden.tsx`. React and react-hook-form are resolved
 * from the React package, so both sides share one copy of each.
 */
import { writeFileSync } from "node:fs";
import { goldenCases } from "../src/testing/fixtures.goldenCases.ts";

const reactPackage = new URL("../../../react/ds-global-form/", import.meta.url);
const resolve = (specifier: string) =>
  Bun.resolveSync(specifier, reactPackage.pathname);
const { createElement } = await import(resolve("react"));
const { renderToStaticMarkup } = await import(resolve("react-dom/server"));
const { FormProvider, useForm } = await import(resolve("react-hook-form"));
const { Field } = await import(
  new URL("dist/esm/index.js", reactPackage).pathname
);

function GoldenForm({
  props,
  error,
}: {
  props: Record<string, unknown>;
  error?: string;
}) {
  const name = props.name as string;
  const methods = useForm({
    errors: error ? { [name]: { type: "manual", message: error } } : undefined,
  });
  return createElement(
    FormProvider,
    methods,
    // biome-ignore lint/suspicious/noExplicitAny: case props are data
    createElement(Field as any, props),
  );
}

const golden: Record<string, string> = {};
for (const [key, { props, error }] of Object.entries(goldenCases)) {
  golden[key] = renderToStaticMarkup(
    createElement(GoldenForm, { props, error }),
  );
}

writeFileSync(
  new URL("../src/testing/fixtures.reactGolden.ts", import.meta.url),
  `// Generated by scripts/captureReactGolden.tsx; do not edit by hand.\nexport const reactGolden: Record<string, string> = ${JSON.stringify(golden, null, 2)};\n`,
);
